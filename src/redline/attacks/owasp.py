"""The two OWASP 2026 catalogs the attack library is tagged with, and the mapping doc built from them.

Names and numbers come from the official sources, not memory: the 2026 LLM list was renumbered
(Excessive Agency moved to LLM03, System Prompt Leakage became LLM08 Hidden Context Exposure,
LLM07 is now Misinformation), so a 2025-numbered tag with a ":2026" suffix silently means the wrong
risk. The Agentic list (ASI01-ASI10) replaced the older ASI-Txx threat ids.

    python -m redline.attacks.owasp      # rewrites docs/owasp_mapping.md (a test checks it is current)
"""

from __future__ import annotations

from redline.attacks.schema import Attack, load_library
from redline.config import ROOT

DOC = ROOT / "docs" / "owasp_mapping.md"

LLM_REPO = "https://github.com/GenAI-Security-Project/GenAI-LLM-Top10/blob/main/2026/final"
LLM_RESOURCE = "https://genai.owasp.org/resource/owasp-genai-llm-top-10-2026/"
ASI_RESOURCE = "https://genai.owasp.org/resource/owasp-top-10-for-agentic-applications-for-2026/"

# id -> (name, source file in the official repo's 2026/final/)
LLM_2026 = {
    "LLM01:2026": ("Prompt Injection", "LLM01_PromptInjection.md"),
    "LLM02:2026": ("Sensitive Information Disclosure", "LLM02_SensitiveInformationDisclosure.md"),
    "LLM03:2026": ("Excessive Agency", "LLM03_ExcessiveAgency.md"),
    "LLM04:2026": ("Supply Chain", "LLM04_SupplyChain.md"),
    "LLM05:2026": ("Data and Model Poisoning", "LLM05_DataModelPoisoning.md"),
    "LLM06:2026": ("Unbounded Consumption", "LLM06_UnboundedConsumption.md"),
    "LLM07:2026": ("Misinformation", "LLM07_Misinformation.md"),
    "LLM08:2026": ("Hidden Context Exposure", "LLM08_HiddenContextExposure.md"),
    "LLM09:2026": ("Vector and Embedding Weaknesses", "LLM09_VectorAndEmbeddingWeaknesses.md"),
    "LLM10:2026": ("Improper Output Handling", "LLM10_ImproperOutputHandling.md"),
}

ASI_2026 = {
    "ASI01:2026": "Agent Goal Hijack",
    "ASI02:2026": "Tool Misuse and Exploitation",
    "ASI03:2026": "Identity and Privilege Abuse",
    "ASI04:2026": "Agentic Supply Chain Vulnerabilities",
    "ASI05:2026": "Unexpected Code Execution",
    "ASI06:2026": "Memory and Context Poisoning",
    "ASI07:2026": "Insecure Inter-Agent Communication",
    "ASI08:2026": "Cascading Failures",
    "ASI09:2026": "Human-Agent Trust Exploitation",
    "ASI10:2026": "Rogue Agents",
}

RATIONALE = """\
How the ids were chosen:

- **Prompt leaks** (system prompt, tool list, policy limits) are LLM08 Hidden Context Exposure, which in 2026
  replaced System Prompt Leakage and covers any hidden operational context. Where the leak is coaxed by an
  instruction, it is also LLM01 and ASI01 (the agent is steered off its support goal).
- **Planted documents and reviews** reach the model through retrieval, so they are LLM09 Vector and Embedding
  Weaknesses (retrieval poisoning) and ASI06 Memory and Context Poisoning, on top of LLM01/ASI01. They are not
  LLM05, which is about training and fine-tuning data.
- **Refunds, coupons and other side effects** are LLM03 Excessive Agency and ASI02 Tool Misuse. Acting on
  another customer's order, or on claimed staff authority, is ASI03 Identity and Privilege Abuse (the agent
  is a confused deputy holding store-wide privileges).
- **Markdown images and links, ANSI escapes** are LLM10 Improper Output Handling, which in 2026 names
  auto-fetching markdown images and terminal escape sequences explicitly.
- Several entries are not exercised by this suite at all: LLM04, LLM05, LLM06, LLM07 and ASI04, ASI05,
  ASI07, ASI08, ASI09, ASI10. There is one agent, no plugins or code execution, and no training step.
"""


def _llm_link(x: str) -> str:
    name, f = LLM_2026[x]
    return f"[{x.split(':')[0]}]({LLM_REPO}/{f})"


def _asi_link(x: str) -> str:
    return f"[{x.split(':')[0]}]({ASI_RESOURCE})"


def render(attacks: list[Attack]) -> str:
    L = ["# OWASP mapping", "",
         "Every attack in `src/redline/attacks/library/` mapped to the **OWASP Top 10 for LLM Applications "
         f"2026** ([announcement and PDF]({LLM_RESOURCE}), [entries in the official repo]({LLM_REPO})) and the "
         f"**OWASP Top 10 for Agentic Applications 2026** ([ASI01-ASI10]({ASI_RESOURCE})). Generated by "
         "`python -m redline.attacks.owasp` from the YAML tags; a test fails if this file is stale.", "",
         "## The lists", "", "| Id | LLM Applications 2026 | Id | Agentic Applications 2026 |", "|---|---|---|---|"]
    for (lid, (lname, _)), (aid, aname) in zip(LLM_2026.items(), ASI_2026.items(), strict=True):
        L.append(f"| {_llm_link(lid)} | {lname} | {_asi_link(aid)} | {aname} |")
    L += ["", RATIONALE, "## Attacks", "", "| Attack | Module | LLM 2026 | Agentic 2026 |", "|---|---|---|---|"]
    for a in attacks:
        llm = ", ".join(f"{_llm_link(x)} {LLM_2026[x][0]}" for x in a.owasp_llm)
        asi = ", ".join(f"{_asi_link(x)} {ASI_2026[x]}" for x in a.owasp_asi) or "—"
        L.append(f"| `{a.id}` | {a.module} | {llm} | {asi} |")
    L += ["", "## Coverage", "", "| Id | Attacks |", "|---|---|"]
    for x in [*LLM_2026, *ASI_2026]:
        n = sum(x in a.owasp_llm or x in a.owasp_asi for a in attacks)
        L.append(f"| {x.split(':')[0]} | {n} |")
    return "\n".join(L) + "\n"


def main() -> None:
    DOC.write_text(render(load_library()), encoding="utf-8")
    print(f"wrote {DOC.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
